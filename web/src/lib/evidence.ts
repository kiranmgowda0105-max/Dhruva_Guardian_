import { jsPDF } from "jspdf";

export interface EvidenceData {
  startedAt: number;
  endedAt: number;
  level: string;
  score: number;
  stagesHit: number[];
  matched: string[];
  language: string;
}

const STAGE_NAMES: Record<number, string> = {
  1: "Authority claim",
  2: "Accusation",
  3: "Isolation and urgency",
  4: "Safe-account payment demand",
  5: "OTP / screen-share",
};

/**
 * Strips non-ASCII characters so the built-in PDF fonts (Helvetica) render cleanly.
 * Non-ASCII phrases (e.g. Kannada / Hindi scripts) are labeled in English.
 */
function sanitizeAscii(text: string): string {
  const sanitized = text.replace(/[^\x20-\x7E]/g, "").trim();
  return sanitized.length > 0 ? sanitized : "[Regional speech pattern detected]";
}

/**
 * Builds and downloads an A4 evidence summary PDF report for reporting to 1930 / cybercrime.gov.in.
 * Uses only English text to guarantee standard font compatibility. Never throws.
 */
export function buildEvidencePdf(data: EvidenceData): void {
  try {
    const doc = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
    });

    const left = 20;
    let y = 22;

    // Title
    doc.setFont("helvetica", "bold");
    doc.setFontSize(18);
    doc.setTextColor(185, 28, 28); // Dark Red
    doc.text("Dhruva Digital Arrest Call Evidence Summary", left, y);

    y += 10;
    doc.setDrawColor(229, 231, 235);
    doc.setLineWidth(0.5);
    doc.line(left, y, 190, y);

    y += 10;
    doc.setFontSize(11);
    doc.setTextColor(31, 41, 55);

    // Call Timing in Asia/Kolkata
    const formatTime = (ts: number) => {
      try {
        return new Date(ts).toLocaleString("en-IN", {
          timeZone: "Asia/Kolkata",
          dateStyle: "medium",
          timeStyle: "medium",
        });
      } catch {
        return new Date(ts).toISOString();
      }
    };

    doc.setFont("helvetica", "bold");
    doc.text("Call Details (Asia/Kolkata Time):", left, y);
    doc.setFont("helvetica", "normal");
    y += 6;
    doc.text(`- Call started: ${formatTime(data.startedAt)}`, left + 4, y);
    y += 6;
    doc.text(`- Call ended:   ${formatTime(data.endedAt)}`, left + 4, y);

    y += 10;
    doc.setFont("helvetica", "bold");
    doc.text("Risk Evaluation:", left, y);
    doc.setFont("helvetica", "normal");
    y += 6;
    doc.text(`- Risk level: ${data.level.toUpperCase()}`, left + 4, y);
    y += 6;
    doc.text(`- Scam risk score: ${data.score} / 100`, left + 4, y);
    y += 6;
    doc.text(`- Detection language: ${sanitizeAscii(data.language)}`, left + 4, y);

    // Stages Hit
    y += 10;
    doc.setFont("helvetica", "bold");
    doc.text("Scam stages detected:", left, y);
    doc.setFont("helvetica", "normal");
    y += 6;

    if (data.stagesHit.length > 0) {
      data.stagesHit.forEach((stageId) => {
        const stageName = STAGE_NAMES[stageId] || `Stage ${stageId}`;
        doc.text(`- Stage ${stageId}: ${stageName}`, left + 4, y);
        y += 6;
      });
    } else {
      doc.text("- None", left + 4, y);
      y += 6;
    }

    // Matched Phrases
    y += 4;
    doc.setFont("helvetica", "bold");
    doc.text("Key phrases flagged:", left, y);
    doc.setFont("helvetica", "normal");
    y += 6;

    if (data.matched.length > 0) {
      const phrasesText = data.matched.map((m) => `"${sanitizeAscii(m)}"`).join(", ");
      const splitPhrases = doc.splitTextToSize(`- ${phrasesText}`, 166);
      doc.text(splitPhrases, left + 4, y);
      y += splitPhrases.length * 6;
    } else {
      doc.text("- None", left + 4, y);
      y += 6;
    }

    // Next Steps Section
    y += 6;
    doc.setDrawColor(254, 202, 202);
    doc.setFillColor(254, 242, 242);
    doc.roundedRect(left, y, 170, 48, 3, 3, "FD");

    y += 7;
    doc.setFont("helvetica", "bold");
    doc.setTextColor(185, 28, 28);
    doc.text("Urgent next steps:", left + 6, y);

    y += 6;
    doc.setFont("helvetica", "normal");
    doc.setTextColor(31, 41, 55);
    doc.text("1. Call 1930 (National Cyber Crime Helpline).", left + 6, y);
    y += 6;
    doc.text("2. File an official cyber fraud complaint at cybercrime.gov.in.", left + 6, y);
    y += 6;
    doc.text("3. Tell your bank to freeze transactions and accounts.", left + 6, y);
    y += 6;
    doc.text("4. Keep screenshots and records of call logs and numbers.", left + 6, y);
    y += 6;
    doc.text("5. Do not transfer any funds or pay any safe-account demands.", left + 6, y);

    // Footer
    y = 280;
    doc.setFontSize(9);
    doc.setTextColor(156, 163, 175);
    doc.text("Generated by Dhruva Guardian. Audio and full transcripts are never saved.", left, y);

    const filename = `dhruva-evidence-${Date.now()}.pdf`;
    doc.save(filename);
  } catch (err) {
    console.error("Failed to build evidence PDF:", err);
  }
}

